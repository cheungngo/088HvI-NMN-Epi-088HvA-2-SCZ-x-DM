def top_gsea_terms(res, n=10):
    if res is None or not hasattr(res, "res2d") or res.res2d is None:
        return None
    df = res.res2d.copy()
    rename = {}
    for c in df.columns:
        lc = c.lower()
        if lc == "term": rename[c] = "Term"
        elif lc == "nes": rename[c] = "NES"
        elif lc in ("fdr q-val", "fdr", "fdr_q-val"): rename[c] = "FDR"
        elif lc in ("nom p-val", "pval", "p-value"): rename[c] = "pval"
    df = df.rename(columns=rename)
    for need, dflt in [("Term", ""), ("NES", np.nan),
                       ("FDR", np.nan), ("pval", np.nan)]:
        if need not in df.columns:
            df[need] = dflt
    for c in ["NES", "FDR", "pval"]:
        df[c] = pd.to_numeric(df[c], errors="coerce")
    df = df.dropna(subset=["NES"])
    up   = df.sort_values("NES", ascending=False).head(n)
    down = df.sort_values("NES", ascending=True).head(n)
    return up, down

