def quantile_normalize_ref(df):
    """Classic quantile normalization: ranks -> mean-of-sorted reference.
    Keeps the original (log2) units, so coefficients are log2 fold-changes,
    and introduces NO tail clipping."""
    V = df.values.astype(float)
    n, m = V.shape
    ref = np.sort(V, axis=0).mean(axis=1)          # reference distribution
    xs  = np.arange(1, n + 1, dtype=float)
    out = np.empty_like(V)
    for j in range(m):
        r = stats.rankdata(V[:, j], method="average")
        out[:, j] = np.interp(r, xs, ref)
    return pd.DataFrame(out, index=df.index, columns=df.columns)

