# %pip -q install scipy
from scipy.stats import hypergeom
import pandas as pd

# ------------------------------------------------------------------
# Knobs — tuned for a tiny (n~15) query. Adjust ONLY these to hit 20-30.
# ------------------------------------------------------------------
SOURCE       = "Robust"
TAG          = "GOBP"
UNIVERSE     = 20000     # background gene count for the hypergeometric test
MIN_OVERLAP  = 1         # KEEP singletons (raising to 2 collapsed to 2 terms)
MAX_LIB_SIZE = 500       # drop huge, vague GO terms
JACCARD_MAX  = 0.5       # collapse terms whose overlap-gene sets are >= this similar
TOP_N        = 30        # hard cap

# ------------------------------------------------------------------
def _hyper_p(k, n_lib, n_query, universe=UNIVERSE):
    """P(X >= k): overlap of an n_query-gene list with an n_lib-gene term."""
    return float(hypergeom.sf(k - 1, universe, n_lib, n_query))

def restrict(recs, n_query,
             min_overlap=MIN_OVERLAP, max_lib=MAX_LIB_SIZE,
             jaccard_max=JACCARD_MAX, top_n=TOP_N):
    # 1. size + overlap prefilter
    cand = [r for r in recs
            if r["n_overlap"] >= min_overlap and r["n_library"] <= max_lib]
    # 2. hypergeometric p as ranking signal (RANK, not FDR-threshold: n is tiny)
    for r in cand:
        r["hyper_p"] = _hyper_p(r["n_overlap"], r["n_library"], n_query)
    cand.sort(key=lambda r: (r["hyper_p"], -r["n_overlap"], r["n_library"]))
    # 3. greedy redundancy collapse on overlap-gene sets
    kept, kept_sets = [], []
    for r in cand:
        s = set(r["overlap_list"])
        redundant = any(
            (len(s | ks) and len(s & ks) / len(s | ks) >= jaccard_max)
            for ks in kept_sets
        )
        if not redundant:
            kept.append(r); kept_sets.append(s)
        if len(kept) >= top_n:
            break
    return kept

