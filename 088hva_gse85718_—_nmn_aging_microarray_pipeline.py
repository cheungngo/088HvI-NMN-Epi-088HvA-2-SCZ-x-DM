def fmt_table(df, cols, n=50):
    if df is None or len(df) == 0:
        return "      (none)"
    cols = [c for c in cols if c in df.columns]
    sub = df[cols].head(n).copy()
    def cell(v, c):
        if isinstance(v, (bool, np.bool_)):
            return "yes" if v else "no"
        if v is None or (isinstance(v, float) and np.isnan(v)):
            return "NA"
        if isinstance(v, (int, np.integer)):
            return str(int(v))
        if isinstance(v, (float, np.floating)):
            return (f"{v:.2e}" if ("p" in c.lower() or "fdr" in c.lower())
                    else f"{v:+.3f}")
        return str(v)
    widths = {c: max(len(c), *(len(cell(v, c)) for v in sub[c])) for c in cols}
    out = ["  ".join(c.ljust(widths[c]) for c in cols),
           "  ".join("-" * widths[c] for c in cols)]
    for _, row in sub.iterrows():
        out.append("  ".join(cell(row[c], c).ljust(widths[c]) for c in cols))
    return "\n".join(out)

