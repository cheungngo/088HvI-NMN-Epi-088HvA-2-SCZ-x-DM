def tissue_ids(tissue):
    return meta.index[meta.tissue == tissue]

def expressed_mask(tissue, bg_q=BG_QUANTILE, min_frac=MIN_FRAC_ABV,
                   min_iqr=MIN_IQR, min_var=MIN_VAR, verbose=True):
    """Drop background / flat probes in this tissue (MouseRef-8 is full of them)."""
    Y   = norm.loc[:, tissue_ids(tissue)]
    bg  = float(np.quantile(Y.values, bg_q))
    frac_above = (Y > bg).mean(axis=1)
    iqr = Y.quantile(0.75, axis=1) - Y.quantile(0.25, axis=1)
    var = Y.var(axis=1)
    mask = (frac_above >= min_frac) & (iqr >= min_iqr) & (var > min_var)
    if verbose:
        log(f"    filter[{tissue}]: bg(q{bg_q:.2f})={bg:.3f} | "
            f"above-bg {int((frac_above >= min_frac).sum())} | "
            f"IQR>={min_iqr} {int((iqr >= min_iqr).sum())} | "
            f"kept {int(mask.sum())}/{len(mask)}")
    return mask, bg

