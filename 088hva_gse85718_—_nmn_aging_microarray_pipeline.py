from scipy.stats import hypergeom
def mito_enrich(df, mito, universe_n=20000):
    if df.empty:
        return np.nan, 0
    n_list = df["gene"].nunique()
    n_mito = len(mito)
    k = len(set(df["gene"]) & mito)
    # P(X >= k)
    p = hypergeom.sf(k - 1, universe_n, n_mito, n_list)
    return p, k

