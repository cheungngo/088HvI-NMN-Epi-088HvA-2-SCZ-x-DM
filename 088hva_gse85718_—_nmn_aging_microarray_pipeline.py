def read_gsea(path):
    sep = "\t" if path.endswith(".tsv") else ","
    try:
        df = pd.read_csv(path, sep=sep)
    except Exception:
        return pd.DataFrame()
    # normalise the columns we care about
    ren = {}
    for c in df.columns:
        lc = c.lower().replace(" ", "").replace("-", "").replace("_", "")
        if lc == "term": ren[c] = "Term"
        elif lc == "nes": ren[c] = "NES"
        elif lc in ("fdrqval", "fdr"): ren[c] = "FDR"
        elif lc in ("nompval", "pval", "pvalue"): ren[c] = "pval"
        elif lc in ("leadgenes", "leadingedge", "ledgenes",
                    "leadinggenes", "genes"): ren[c] = "Lead_genes"
    return df.rename(columns=ren)

