def fmt_top_table(df, cols, n=20, floatfmt="{:+.3f}", trunc=70):
    sub = df[cols].head(n).copy()
    def cell(c, v):
        if isinstance(v, (bool, np.bool_)):        return str(bool(v))
        if isinstance(v, (int, np.integer)):       return str(int(v))
        if isinstance(v, (float, np.floating)):
            if not np.isfinite(v):                 return "NA"
            return f"{v:.3e}" if SCI(c) else floatfmt.format(v)
        return str(v)[:trunc]
    if len(sub) == 0:
        return "(no rows)"
    body = {c: [cell(c, v) for v in sub[c]] for c in cols}
    w = {c: max([len(str(c))] + [len(x) for x in body[c]]) for c in cols}
    lines = ["  ".join(str(c).ljust(w[c]) for c in cols),
             "  ".join("-" * w[c] for c in cols)]
    for i in range(len(sub)):
        lines.append("  ".join(body[c][i].ljust(w[c]) for c in cols))
    return "\n".join(lines)

def top_gsea(res, n=10):
    if res is None or getattr(res, "res2d", None) is None: return None
    df = res.res2d.copy(); ren = {}
    for c in df.columns:
        lc = c.lower()
        if lc == "term": ren[c] = "Term"
        elif lc == "nes": ren[c] = "NES"
        elif lc in ("fdr q-val", "fdr", "fdr_q-val"): ren[c] = "FDR"
        elif lc in ("nom p-val", "pval", "p-value"): ren[c] = "pval"
    df = df.rename(columns=ren)
    for k, v in [("Term", ""), ("NES", np.nan), ("FDR", np.nan), ("pval", np.nan)]:
        if k not in df.columns: df[k] = v
    for k in ["NES", "FDR", "pval"]:
        df[k] = pd.to_numeric(df[k], errors="coerce")
    df = df.dropna(subset=["NES"])
    return (df.sort_values("NES", ascending=False).head(n),
            df.sort_values("NES", ascending=True).head(n))

