GROUP_ORDER = ["Control_6M", "Control_12M", "NMN_6M", "NMN_12M"]

def group_mean_table(tissue, genes):
    sub = meta[meta.tissue == tissue]
    cols = {}
    for label in GROUP_ORDER:
        tr, ag = label.split("_")
        ids = sub[(sub.treatment == tr) & (sub.age == ag)].index
        cols[label] = norm.loc[genes, ids].mean(axis=1)
    return pd.DataFrame(cols)

def artifact_flags(tissue, genes):
    """Flag on/off-background behaviour: big between-group jump with ~no
    within-group scatter, and/or expression sitting at the background floor."""
    sub = meta[meta.tissue == tissue]
    Y   = norm.loc[genes, sub.index]
    bg  = FILTER_STATS[tissue]["background"]
    within_sd = []
    for label in GROUP_ORDER:
        tr, ag = label.split("_")
        ids = sub[(sub.treatment == tr) & (sub.age == ag)].index
        within_sd.append(Y[ids].std(axis=1))
    pooled_sd = pd.concat(within_sd, axis=1).mean(axis=1)
    G = group_mean_table(tissue, genes)
    span = G.max(axis=1) - G.min(axis=1)
    onoff = (span > 6 * (pooled_sd + 1e-3)) & (G.min(axis=1) <= bg)
    low   = Y.median(axis=1) <= bg
    flags = np.where(onoff, "ON_OFF_BACKGROUND",
             np.where(low, "LOW_EXPRESSED", ""))
    return pd.Series(flags, index=genes)

