import gseapy as gp
GENE_SETS = ["MSigDB_Hallmark_2020", "KEGG_2019_Mouse", "GO_Biological_Process_2021"]

def run_gsea(tissue):
    de = de_results[tissue].dropna(subset=["t_interaction"])
    rnk = (de.assign(gene=de.gene.str.upper())[["gene", "t_interaction"]]
             .groupby("gene", as_index=False).mean()
             .sort_values("t_interaction", ascending=False))
    ties = 1 - rnk.t_interaction.nunique() / len(rnk)
    log(f"    GSEA {tissue}: {len(rnk)} genes ranked by interaction t "
        f"({ties*100:.2f}% tied values)")
    try:
        res = gp.prerank(rnk=rnk, gene_sets=GENE_SETS, permutation_num=1000,
                         min_size=10, max_size=500, outdir=f"results/GSEA/{tissue}",
                         seed=42, no_plot=True, verbose=False, threads=4)
        res.res2d.to_csv(f"results/GSEA/GSEA_{tissue}.tsv", sep="\t", index=False)
        log(f">>> GSEA {tissue}: {len(res.res2d)} terms tested")
        return res
    except Exception as e:
        warn(f"GSEA {tissue} skipped (Enrichr/network issue): {e}")
        return None

