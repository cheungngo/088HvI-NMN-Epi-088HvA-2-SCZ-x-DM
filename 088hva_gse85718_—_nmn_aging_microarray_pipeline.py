def rescue_select(de, mode):
    d = de.copy()
    # positive rescue fraction == interaction opposes the aging slope
    with np.errstate(divide="ignore", invalid="ignore"):
        d["rescue_frac"] = -d.coef_interaction / d.coef_age_Control.replace(0, np.nan)
    d["rescue_frac"] = d["rescue_frac"].fillna(0.0)
    if mode == "strict":
        c = STRICT
        sel = ((d.fdr_age_Control < c["fdr_age"]) & (d.fdr_interaction < c["fdr_int"]))
    else:
        c = RELAX
        sel = ((d.p_age_Control < c["p_age"]) & (d.p_interaction < c["p_int"]))
    sel &= (d.coef_age_Control.abs() >= c["min_abs_age"])
    sel &= (d.rescue_frac >= c["min_rescue_frac"])
    return d[sel].sort_values("p_interaction")

