def vectorized_ols(Y, X, min_var=MIN_VAR):
    """Y: genes x n ; X: n x p -> beta, se, t, p, estimable  (all NaN-free)."""
    n, p = X.shape
    XtX_inv = np.linalg.pinv(X.T @ X)          # pinv: tolerates rank deficiency
    beta  = Y @ X @ XtX_inv                    # genes x p
    resid = Y - beta @ X.T
    dof   = n - p
    sigma2 = (resid ** 2).sum(axis=1) / dof
    sigma2 = np.maximum(sigma2, 0.0)
    se = np.sqrt(np.outer(sigma2, np.diag(XtX_inv)))
    with np.errstate(divide="ignore", invalid="ignore"):
        tvals = np.divide(beta, se, out=np.zeros_like(beta), where=(se > 0))
    tvals = np.where(np.isfinite(tvals), tvals, 0.0)
    estimable = sigma2 > min_var               # zero-variance / perfect fit
    tvals[~estimable, :] = 0.0                 # -> p = 1, never NaN
    pvals = 2 * stats.t.sf(np.abs(tvals), dof)
    pvals = np.clip(np.nan_to_num(pvals, nan=1.0), 0.0, 1.0)
    return beta, se, tvals, pvals, estimable

def bh_fdr(p):
    """NaN-proof Benjamini-Hochberg. statsmodels returns ALL-NaN if any p is NaN."""
    p = np.asarray(p, dtype=float)
    out = np.ones(p.shape, dtype=float)
    ok = np.isfinite(p)
    if ok.any():
        out[ok] = multipletests(p[ok], method="fdr_bh")[1]
    return out

