def polarity_of(df):
    if df.empty: return (np.nan, 0, 0)
    w = (df.pivot_table(index=["GeneSet","Gene"], columns="Disease",
                        values="Z_score", aggfunc="first").dropna(subset=[D1,D2])
         if {D1,D2}.issubset(df["Disease"].unique()) else pd.DataFrame())
