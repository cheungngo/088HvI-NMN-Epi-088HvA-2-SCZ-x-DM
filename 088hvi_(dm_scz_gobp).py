def passport(gene_df):
    rows = []
    for gene, sub in gene_df.groupby("Gene"):
        wide = sub.pivot_table(index="GeneSet", columns="Disease",
                               values="Z_score", aggfunc="first")
        if not {D1, D2}.issubset(getattr(wide, "columns", [])): continue
        w = wide.dropna(subset=[D1, D2])
        if w.empty: continue
        z1, z2 = w[D1], w[D2]
        both = (z1.abs()>=Z_SIG) & (z2.abs()>=Z_SIG)
        same = np.sign(z1) == np.sign(z2)
        pol_med = float(np.sign(z1.median()) * np.sign(z2.median()))
        rows.append({
            "Gene": gene, "n_sets_paired": len(w),
            "n_both_sig": int(both.sum()),
            "n_divergent": int((both & ~same).sum()),
            "n_convergent": int((both & same).sum()),
            f"median_{D1}": float(z1.median()), f"median_{D2}": float(z2.median()),
            f"max_{D1}": float(z1.abs().max())*(np.sign(z1.median()) or 1),
            f"max_{D2}": float(z2.abs().max())*(np.sign(z2.median()) or 1),
            "polarity": pol_med,
            "frac_divergent": ((both & ~same).sum()/both.sum() if both.sum() else np.nan),
            "n_ext": int((sub["Z_score"].abs()>EXT).sum()),
            "influential_any": bool(sub.get("Influential", pd.Series(False,index=sub.index)).astype(bool).any()),
            "signflip_any": bool(sub.get("Sign_Change", pd.Series(False,index=sub.index)).astype(bool).any()),
            "max_pct_change": (float(sub["Pct_Change_Stouffer"].abs().max())
                               if "Pct_Change_Stouffer" in sub else np.nan),
        })
    return pd.DataFrame(rows)

