def classify(wide, zcut):
    d = wide.dropna(subset=[D1, D2]).copy()
    both = (d[D1].abs() >= zcut) & (d[D2].abs() >= zcut)
    prod = d[D1] * d[D2]
    n_conv = int((both & (prod > 0)).sum())
    n_div  = int((both & (prod < 0)).sum())
    n_p1   = int(((d[D1].abs() >= zcut) & (d[D2].abs() < zcut)).sum())
    n_p2   = int(((d[D2].abs() >= zcut) & (d[D1].abs() < zcut)).sum())
    return pd.Series({
        "n_paired": len(d), "n_conv": n_conv, "n_div": n_div,
        "n_priv1": n_p1, "n_priv2": n_p2,
        "frac_div": (n_div / (n_conv + n_div) if (n_conv + n_div) else np.nan),
    })

def polarity(df):
    if df.empty or not {D1, D2}.issubset(df.get("Disease", pd.Series()).unique()):
        return (np.nan, 0, 0)
    w = (df.pivot_table(index=["GeneSet", "Gene"], columns="Disease",
                        values="Z_score", aggfunc="first").dropna(subset=[D1, D2]))
    if w.empty or not {D1, D2}.issubset(w.columns):
        return (np.nan, 0, 0)
    both = (w[D1].abs() >= Z_SIG) & (w[D2].abs() >= Z_SIG)
    wb = w[both]
    if wb.empty:
        return (np.nan, 0, 0)
    div = int((wb[D1] * wb[D2] < 0).sum())
    con = int((wb[D1] * wb[D2] > 0).sum())
    return ((con - div) / (con + div) if (con + div) else np.nan, con, div)

